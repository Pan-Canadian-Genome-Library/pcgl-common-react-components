import {
  Children,
  Fragment,
  isValidElement,
  useCallback,
  useEffect,
  useId,
  useMemo,
  useRef,
  useState,
  type ComponentPropsWithRef,
  type CSSProperties,
  type ReactElement,
  type ReactNode,
} from 'react';
import { cx } from 'class-variance-authority';
import { buttonReset, focusRing, listReset } from '../lib/reset';
import { HeaderContext, type HeaderLinkComponent, type HeaderTranslator } from './header-context';
import { CloseIcon, MenuIcon } from './icons';
import { SkipLinks, type SkipLinkItem } from './skip-links';

export interface HeaderProps extends ComponentPropsWithRef<'header'> {
  logo: ReactNode;
  logoHref?: string;
  nav?: ReactNode;
  language?: ReactNode;
  actions?: ReactNode;
  account?: ReactNode;
  translator: HeaderTranslator;
  linkComponent?: HeaderLinkComponent;
  skipLinks?: SkipLinkItem[];
  brand?: string;
}

interface HeaderStyle extends CSSProperties {
  '--pcgl-header-brand'?: string;
}

/** TODO: Autogenerated code maybe is not needed */
const flatten = (children: ReactNode): ReactNode[] => {
  const items: ReactNode[] = [];
  Children.toArray(children).forEach((child) => {
    if (isValidElement(child) && child.type === Fragment) {
      items.push(...flatten((child as ReactElement<{ children?: ReactNode }>).props.children));
    } else {
      items.push(child);
    }
  });
  return items;
};

const NavList = ({
  items,
  label,
  className,
}: {
  items: ReactNode[];
  label: string;
  className: string;
}) => (
  <nav aria-label={label} className={cx('pcgl-header-nav', className)}>
    <ul
      className={cx(listReset, 'pcgl:flex pcgl:gap-x-8 pcgl:max-md:flex-col pcgl:max-md:gap-y-1')}
    >
      {items.map((item, index) => (
        <li key={index}>{item}</li>
      ))}
    </ul>
  </nav>
);

export const Header = ({
  logo,
  logoHref = '/',
  nav,
  language,
  actions,
  account,
  translator,
  linkComponent = 'a',
  skipLinks,
  brand,
  className,
  style,
  ...props
}: HeaderProps) => {
  const [panelOpen, setPanelOpen] = useState(false);
  const toggleRef = useRef<HTMLButtonElement>(null);
  const panelId = useId();

  const closePanel = useCallback(() => setPanelOpen(false), []);
  const context = useMemo(
    () => ({ translator, linkComponent, closePanel }),
    [translator, linkComponent, closePanel],
  );

  useEffect(() => {
    if (!panelOpen) return;
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === 'Escape') {
        setPanelOpen(false);
        toggleRef.current?.focus();
      }
    };
    document.addEventListener('keydown', onKeyDown);
    return () => document.removeEventListener('keydown', onKeyDown);
  }, [panelOpen]);

  const navItems = flatten(nav);
  const hasNav = navItems.length > 0;
  const hasActions = flatten(actions).length > 0;
  const hasPanel = hasNav || hasActions;
  const showDivider = Boolean(language) && (hasActions || Boolean(account));
  const navLabel = translator('header.nav');
  const Link = linkComponent;

  const links = skipLinks ?? [
    { href: '#main-content', label: translator('header.skipLinks.main') },
    { href: '#about-us-footer', label: translator('header.skipLinks.footer') },
  ];

  const headerStyle: HeaderStyle = brand
    ? { '--pcgl-header-brand': brand, ...style }
    : { ...style };

  return (
    <HeaderContext.Provider value={context}>
      <header
        {...props}
        style={headerStyle}
        className={cx(
          'pcgl-header',
          'pcgl:relative pcgl:z-[1000] pcgl:border-b',
          'pcgl:border-[color:var(--pcgl-header-border,#929497)] pcgl:bg-[color:var(--pcgl-header-bg,#fff)] pcgl:text-[color:var(--pcgl-header-text,#000)]',
          className,
        )}
      >
        <SkipLinks links={links} />
        <div className="pcgl-header-bar pcgl:flex pcgl:h-[var(--pcgl-header-height,4rem)] pcgl:items-center pcgl:gap-4 pcgl:px-4 pcgl:md:gap-8 pcgl:md:px-8">
          <Link
            href={logoHref}
            aria-label={translator('header.home')}
            className={cx(
              'pcgl-header-logo',
              focusRing,
              'pcgl:flex pcgl:shrink-0 pcgl:items-center pcgl:rounded-sm pcgl:text-inherit pcgl:no-underline',
            )}
          >
            {logo}
          </Link>

          {hasNav ? (
            <NavList items={navItems} label={navLabel} className="pcgl:max-md:hidden" />
          ) : null}

          <div className="pcgl:ml-auto pcgl:flex pcgl:items-center pcgl:gap-2 pcgl:md:gap-4">
            {language ? <div className="pcgl-header-language pcgl:flex">{language}</div> : null}
            {showDivider ? (
              <div
                aria-hidden="true"
                className="pcgl-header-divider pcgl:h-10 pcgl:w-px pcgl:bg-[color:var(--pcgl-header-border,#929497)] pcgl:max-md:hidden"
              />
            ) : null}
            {hasActions ? (
              <div className="pcgl-header-actions pcgl:flex pcgl:items-center pcgl:gap-4 pcgl:max-md:hidden">
                {actions}
              </div>
            ) : null}
            {account ? <div className="pcgl-header-account pcgl:flex">{account}</div> : null}
            {hasPanel ? (
              <button
                ref={toggleRef}
                type="button"
                aria-expanded={panelOpen}
                aria-controls={panelId}
                aria-label={translator(panelOpen ? 'header.menu.close' : 'header.menu.open')}
                onClick={() => setPanelOpen((open) => !open)}
                className={cx(
                  'pcgl-header-toggle',
                  buttonReset,
                  focusRing,
                  'pcgl:flex pcgl:size-10 pcgl:items-center pcgl:justify-center pcgl:rounded-md pcgl:border-0 pcgl:bg-transparent pcgl:text-2xl pcgl:md:hidden',
                  'pcgl:text-[color:var(--pcgl-header-text,#000)]',
                )}
              >
                {panelOpen ? <CloseIcon /> : <MenuIcon />}
              </button>
            ) : null}
          </div>
        </div>

        {hasPanel ? (
          <div
            id={panelId}
            hidden={!panelOpen}
            className={cx(
              'pcgl-header-panel pcgl:md:hidden',
              'pcgl:border-t pcgl:border-[color:var(--pcgl-header-border,#929497)] pcgl:px-4 pcgl:py-4',
            )}
          >
            {hasNav ? <NavList items={navItems} label={navLabel} className="" /> : null}
            {hasActions ? (
              <div className="pcgl-header-actions pcgl:mt-2 pcgl:flex pcgl:flex-col pcgl:items-start pcgl:gap-1 pcgl:border-t pcgl:border-[color:var(--pcgl-header-border,#929497)] pcgl:pt-2">
                {actions}
              </div>
            ) : null}
          </div>
        ) : null}
      </header>
    </HeaderContext.Provider>
  );
};
